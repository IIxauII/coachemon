#!/bin/sh
# Writes results.md next to this script: every table the findings cite, from the harnesses, with `prototype.patch`
# applied. Run from the repo root.
D=docs/research/862-double-status-price
S="$D/double-score.mjs"
P="$D/scene-trace.mjs"
{
  echo "# #862 results"
  echo
  echo "Generated by \`results.sh\` with \`prototype.patch\` applied. Foe 0 is the first foe listed, foe 1 the second."
  echo
  echo "## 1. The field hypothesis against the own duel"
  for m in protect spore twave; do node "$S" --credit --move "$m"; done
  echo
  echo "## 2. Protect in the double, per design"
  node "$S" today "own duel" own "own + redirect" "own + redirect + singles prices" proposed
  echo
  echo "## 3. Each plan's terms (the redirect)"
  node "$S" --terms today own "own + redirect" proposed
  echo
  echo "## 4. Sleep and paralysis in the double, today and proposed"
  node "$S" --move spore today proposed
  node "$S" --move twave today proposed
  echo
  echo "## 5. The two designs on perturbed turns"
  echo
  node "$D/sweep.mjs"
  echo
  echo "## 6. Golden scenes, traced"
  echo
  echo "#262's Spore scene, today and proposed:"
  node "$P" plannertest '^doubles: a status play' '{}'
  node "$P" plannertest '^doubles: a status play' '{"dplay":"own","pfield":true,"redir":"then","dcredit":true}'
  echo
  echo "#320's scene, Breloom faster than Machamp, today and proposed:"
  node "$P" plannertest 'partner is scored on the hypothesis' '{}'
  node "$P" plannertest 'partner is scored on the hypothesis' '{"dplay":"own","pfield":true,"redir":"then","dcredit":true}'
  echo
  echo "#283's certainty axis at 0.5, today and with the singles prices in the double:"
  node "$P" plannertest "partner's KO is not certain" '{}'
  node "$P" plannertest "partner's KO is not certain" '{"hp":1,"loss":4,"scope":"all"}'
} 2>&1 | grep -vi localstorage | grep -v '^ASSERT FAIL' > "$D/results.md"
