#!/bin/sh
# Writes results.md next to this script: every table the findings cite, from the harnesses, with `prototype.patch`
# applied. Run from the repo root.
DIR=docs/research/862-double-status-price
SCORE="$DIR/double-score.mjs"
TRACE="$DIR/scene-trace.mjs"
TESTS=skills/coachemon/scripts/test
PROPOSED='{"dplay":"own","pfield":true,"redir":"then","dcredit":true}'
# #262's Spore field with Breloom faster than Machamp, as a throwaway copy beside the test it comes from.
FAST="$TESTS/zz862fast.mjs"
trap 'rm -f "$FAST"' EXIT
sed 's/\[250, 200, 110, 60, 90, 100\], \[\["Seed Bomb", "Grass", 80, "P"\], SPORE\]/[250, 200, 110, 60, 90, 150], [["Seed Bomb", "Grass", 80, "P"], SPORE]/' \
  "$TESTS/plannertest.mjs" > "$FAST"
{
  echo "# #862 results"
  echo
  echo "Generated by \`results.sh\` with \`prototype.patch\` applied. Foe 0 is the first foe listed, foe 1 the second."
  echo
  echo "## 1. The field hypothesis against the own duel"
  for m in protect spore twave; do node "$SCORE" --credit --move "$m"; done
  echo
  echo "## 2. Protect in the double, per design"
  node "$SCORE" today "own duel" own "own + redirect" "own + redirect + singles prices" proposed
  node "$SCORE" --left proposed
  echo
  echo "## 3. Each plan's terms (the redirect)"
  node "$SCORE" --terms today own "own + redirect" "own + redirect + singles prices" proposed
  node "$SCORE" --duel own
  echo
  echo "## 4. Sleep and paralysis in the double, today and proposed"
  node "$SCORE" --move spore today proposed
  node "$SCORE" --move twave today proposed
  node "$SCORE" --move spore --terms today proposed
  echo
  echo "## 5. The two designs on perturbed turns"
  echo
  node "$DIR/sweep.mjs"
  echo
  echo "## 6. Golden scenes, traced"
  echo
  echo "#262's Spore scene, today and proposed:"
  node "$TRACE" plannertest '^doubles: a status play' '{}'
  node "$TRACE" plannertest '^doubles: a status play' "$PROPOSED"
  echo
  echo "#320's scene (Breloom faster than Machamp, its own damage table), today and proposed:"
  node "$TRACE" plannertest 'partner is scored on the hypothesis' '{}'
  node "$TRACE" plannertest 'partner is scored on the hypothesis' "$PROPOSED"
  echo
  echo "#262's Spore field with Breloom faster than Machamp (spe 150), today and proposed, with the assertions that fail:"
  node "$TRACE" zz862fast '^doubles: a status play' '{}'
  node "$TRACE" zz862fast '^doubles: a status play' "$PROPOSED"
  echo
  echo "#283's certainty axis at 0.5, today and with the singles prices in the double:"
  node "$TRACE" plannertest "partner's KO is not certain" '{}'
  node "$TRACE" plannertest "partner's KO is not certain" '{"hp":1,"loss":4,"scope":"all"}'
  echo
  echo "## 7. Blast radius: golden diffs under each set of switches"
  for cfg in '{}' '{"hp":1,"loss":4}' "$PROPOSED" '{"dplay":"own","pfield":true,"redir":"then","dcredit":true,"protect":"double"}' \
    '{"hp":1,"loss":4,"dplay":"own","pfield":true,"redir":"then","dcredit":true,"protect":"double"}' \
    '{"hp":1,"loss":4,"scope":"all","dplay":"own","pfield":true,"redir":"then","protect":"double"}' \
    '{"hp":1,"loss":4,"scope":"all","surv":true}'; do
    echo
    echo "### \`$cfg\`"
    echo
    echo '```diff'
    node "$DIR/blast.mjs" --soft "$cfg"
    echo '```'
  done
} 2>&1 | grep -vi localstorage > "$DIR/results.md"
