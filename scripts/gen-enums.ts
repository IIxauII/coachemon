const { values: args } = parseArgs({
  options: { version: { type: "string" }, source: { type: "string" }, check: { type: "boolean" } },
});

const reviewed = JSON.parse(readFileSync(REVIEWED, "utf8")) as { pinned: { gameVersion: string } };
const version = args.version ?? reviewed.pinned.gameVersion;
const tag = `v${version}`;

async function read(file: string): Promise<string> {
  if (args.source) return readFileSync(path.join(path.resolve(args.source), file), "utf8");
  const cache = path.resolve(".cache/pokerogue-src", tag, file);
  if (existsSync(cache)) return readFileSync(cache, "utf8");
  const res = await fetch(`${RAW}/${tag}/${file}`);
  if (!res.ok) throw new Error(`${res.status} fetching ${file} at ${tag}`);
  const text = await res.text();
  mkdirSync(path.dirname(cache), { recursive: true });
  writeFileSync(cache, text);
  return text;
}

const parsed: Record<string, [string, number][]> = {};
for (const [name, file] of Object.entries(ENUMS)) parsed[name] = parseEnum(await read(file), name);

const HEADER = ["// GENERATED by scripts/gen-enums.ts — do not edit.", `// Source: pagefaultgames/pokerogue at ${tag}.`, ""];
const counts = (tables: Record<string, unknown[]>) =>
  Object.entries(tables).map(([name, members]) => `${name}=${members.length}`).join(", ");

const lines: string[] = [
  ...HEADER,
  `export const GENERATED_GAME_VERSION = ${JSON.stringify(version)};`,
  "",
];
for (const [name, members] of Object.entries(parsed)) {
  lines.push(`export const ${name} = {`);
  for (const [k, v] of members) lines.push(`  ${k}: ${v},`);
  lines.push("} as const;", `export type ${name} = (typeof ${name})[keyof typeof ${name}];`, "");
}
lines.push(
  "/** int → member name, for each table. */",
  "export const NAMES = {",
  ...Object.keys(parsed).map(name => `  ${name}: invert(${name}),`),
  "} as const;",
  "",
  "function invert(table: Record<string, number>): Record<number, string> {",
  "  const out: Record<number, string> = {};",
  "  for (const [k, v] of Object.entries(table)) out[v] = k;",
  "  return out;",
  "}",
  "",
);
// Never into `generated.ts`: the HUD bundler takes every object exported there for an enum table.
const registryBody = (await read("src/modifier/modifier-type.ts")).match(
  /\nconst modifierTypeInitObj = Object\.freeze\(\{([\s\S]*?)\n\}\);/,
)?.[1];
if (registryBody === undefined) throw new Error("modifierTypeInitObj not found");
const modifiers = {
  MODIFIER_TYPE_IDS: [...registryBody.matchAll(/^ {2}([A-Z][A-Z0-9_]*):/gm)].map(m => m[1]),
  MODIFIER_CLASSES: [...(await read("src/modifier/modifier.ts")).matchAll(/^export (?:abstract )?class (\w+)/gm)].map(
    m => m[1],
  ),
};
const modifierLines = [...HEADER];
for (const [name, members] of Object.entries(modifiers)) {
  modifierLines.push(`export const ${name}: ReadonlySet<string> = new Set([`, ...members.map(m => `  "${m}",`), "]);", "");
}

const outputs: [URL, string, string][] = [
  [OUT, lines.join("\n"), counts(parsed)],
  [MODIFIERS_OUT, modifierLines.join("\n"), counts(modifiers)],
];
for (const [out, text, tally] of outputs) {
  const relOut = path.relative(process.cwd(), new URL(out).pathname);
  if (args.check) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
      console.error(`${relOut} is stale — run \`npm run enums:gen\``);
      process.exit(1);
    }
    console.log(`${relOut} up to date at ${tag}: ${tally}`);
  } else {
    mkdirSync(path.dirname(new URL(out).pathname), { recursive: true });
    writeFileSync(out, text);
    console.log(`wrote ${relOut} from ${tag}: ${tally}`);
  }
}
